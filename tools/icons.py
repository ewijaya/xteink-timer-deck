#!/usr/bin/env python3
"""Offline Lucide SVG flattening, preserving Pebble 0.7.0 icon order (ISC)."""
import json,math,re,sys,xml.etree.ElementTree as ET
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
N=re.compile(r'[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?')
def arc(p,rx,ry,angle,large,sweep,q):
 rx,ry=abs(rx),abs(ry)
 if not rx or not ry or p==q:return [q]
 phi=math.radians(angle);co,si=math.cos(phi),math.sin(phi);dx,dy=(p[0]-q[0])/2,(p[1]-q[1])/2;x,y=co*dx+si*dy,-si*dx+co*dy
 scale=x*x/(rx*rx)+y*y/(ry*ry)
 if scale>1:rx*=math.sqrt(scale);ry*=math.sqrt(scale)
 factor=math.sqrt(max(0,(rx*rx*ry*ry-rx*rx*y*y-ry*ry*x*x)/(rx*rx*y*y+ry*ry*x*x)))*(1 if large!=sweep else -1)
 cx,cy=factor*rx*y/ry,-factor*ry*x/rx
 center=(co*cx-si*cy+(p[0]+q[0])/2,si*cx+co*cy+(p[1]+q[1])/2)
 a=math.atan2((y-cy)/ry,(x-cx)/rx);b=math.atan2((-y-cy)/ry,(-x-cx)/rx);delta=(b-a)%(2*math.pi)
 if not sweep:delta-=2*math.pi
 count=max(1,math.ceil(abs(delta)/(math.pi/8)))
 return [(center[0]+co*rx*math.cos(a+delta*k/count)-si*ry*math.sin(a+delta*k/count),center[1]+si*rx*math.cos(a+delta*k/count)+co*ry*math.sin(a+delta*k/count)) for k in range(1,count+1)]
def path(s):
 i=0;p=(0,0);start=p;cmd=None;paths=[];line=[];control=None;previous=''
 def skip():
  nonlocal i
  while i<len(s) and (s[i].isspace() or s[i]==','):i+=1
 def number(flag=False):
  nonlocal i
  skip()
  if flag:assert s[i] in '01';v=int(s[i]);i+=1;return v
  m=N.match(s,i);assert m,(s,i);i=m.end();return float(m[0])
 while True:
  skip()
  if i>=len(s):break
  if s[i].isalpha():cmd=s[i];i+=1
  assert cmd;op=cmd.upper();relative=cmd.islower();old=p
  def point():
   x,y=number(),number();return (x+p[0],y+p[1]) if relative else (x,y)
  if op=='Z':line.append(start);p=start;cmd=None
  elif op=='M':
   q=point()
   if line:paths.append(line)
   line=[q];p=q;start=q;cmd='l' if relative else 'L'
  elif op=='L':p=point();line.append(p)
  elif op=='H':v=number();p=(p[0]+v if relative else v,p[1]);line.append(p)
  elif op=='V':v=number();p=(p[0],p[1]+v if relative else v);line.append(p)
  elif op=='A':
   rx,ry,angle=number(),number(),number();large,sweep=number(True),number(True);q=point();line+=arc(p,rx,ry,angle,large,sweep,q);p=q
  elif op in ('C','S','Q','T'):
   family=('C','S') if op in ('C','S') else ('Q','T')
   reflect=(2*p[0]-control[0],2*p[1]-control[1]) if control and previous in family else p
   a=point() if op in ('C','Q') else reflect
   b=point() if op in ('C','S') else None
   q=point()
   for k in range(1,9):
    t=k/8;u=1-t
    line.append(tuple(u*u*u*p[j]+3*u*u*t*a[j]+3*u*t*t*b[j]+t*t*t*q[j] if b else u*u*p[j]+2*u*t*a[j]+t*t*q[j] for j in (0,1)))
   control=b or a;p=q
  else:raise ValueError(op)
  previous=op
 if line:paths.append(line)
 return paths
def flatten(file):
 lines=[]
 for e in ET.parse(file).getroot():
  tag=e.tag.split('}')[-1];a=e.attrib;v=lambda k,default=0:float(a.get(k,default))
  if tag=='path':lines+=path(a['d'])
  elif tag in ('circle','ellipse'):
   rx,ry=(v('r'),v('r')) if tag=='circle' else (v('rx'),v('ry'));lines.append([(v('cx')+rx*math.cos(k*math.pi/8),v('cy')+ry*math.sin(k*math.pi/8)) for k in range(17)])
  elif tag=='rect':
   x,y,w,h,r=v('x'),v('y'),v('width'),v('height'),v('rx');lines+=path(f'M{x+r} {y}h{w-2*r}a{r} {r} 0 0 1 {r} {r}v{h-2*r}a{r} {r} 0 0 1 {-r} {r}h{-w+2*r}a{r} {r} 0 0 1 {-r} {-r}v{-h+2*r}a{r} {r} 0 0 1 {r} {-r}Z')
  elif tag=='line':lines.append([(v('x1'),v('y1')),(v('x2'),v('y2'))])
  elif tag in ('polyline','polygon'):
   ns=[float(x) for x in N.findall(a['points'])];pts=list(zip(ns[::2],ns[1::2]));lines.append(pts+([pts[0]] if tag=='polygon' else []))
  else:raise ValueError(tag)
 out=[]
 for line in lines:
  pts=[]
  for x,y in line:
   q=(max(0,min(94,round(x*94/24))),max(0,min(94,round(y*94/24))))
   if not pts or q!=pts[-1]:pts.append(q)
  if len(pts)==1:pts.append((min(94,pts[0][0]+1),pts[0][1]))
  for i in range(0,len(pts)-1,127):out.append(pts[i:i+128])
 assert len(out)<=12 and sum(map(len,out))<=160,(file,len(out),sum(map(len,out)))
 return out
def main():
 result=['-- Generated by tools/icons.py; Lucide ISC, baseline 202dbc6.\nreturn {\n']
 for name,file in json.loads((ROOT/'assets/icons/order.json').read_text()):
  strings=[''.join(chr(32+v) for p in line for v in p) for line in flatten(ROOT/'assets/icons/lucide'/f'{file}.svg')]
  result.append(' {'+','.join(json.dumps(s) for s in strings)+'}, -- '+name+'\n')
 result.append('}\n');raw=''.join(result);target=ROOT/'app/lib/gen/icons.lua'
 if '--check' in sys.argv:assert target.read_text()==raw,'stale icons'
 else:target.write_text(raw)
 print('HOST MOCK: 30 vector icons checked' if '--check' in sys.argv else 'Generated 30 vector icons')
if __name__=='__main__':main()
